-- THIET KE MINH HOA. Chua chay tren Oracle.
-- Chi dung trong schema hoc tap trong; khong chay tren schema Hibernate da tao.
-- VARCHAR2(... CHAR): gioi han theo ky tu.

CREATE TABLE LOAI_MON (
  MA_LOAI NUMBER,
  TEN_LOAI VARCHAR2(100 CHAR) NOT NULL,
  MO_TA VARCHAR2(255 CHAR),
  TRANG_THAI VARCHAR2(20 CHAR),
  PRIMARY KEY (MA_LOAI)
);

CREATE TABLE NHAN_VIEN (
  MA_NV NUMBER,
  HO_TEN VARCHAR2(100 CHAR) NOT NULL,
  GIOI_TINH VARCHAR2(10 CHAR),
  SDT VARCHAR2(15 CHAR),
  CHUC_VU VARCHAR2(50 CHAR),
  LUONG NUMBER(12,2),
  NGAY_VAO_LAM DATE,
  PRIMARY KEY (MA_NV),
  CHECK (LUONG>=0)
);

CREATE TABLE KHACH_HANG (
  MA_KH NUMBER,
  HO_TEN VARCHAR2(100 CHAR) NOT NULL,
  SDT VARCHAR2(15 CHAR),
  EMAIL VARCHAR2(100 CHAR),
  DIEM_TICH_LUY NUMBER(10,0) DEFAULT 0,
  PRIMARY KEY (MA_KH),
  CHECK (DIEM_TICH_LUY>=0)
);

CREATE TABLE BAN_AN (
  MA_BAN NUMBER,
  TEN_BAN VARCHAR2(50 CHAR) NOT NULL,
  SO_CHO NUMBER(3) NOT NULL,
  KHU_VUC VARCHAR2(50 CHAR),
  TRANG_THAI VARCHAR2(20 CHAR),
  PRIMARY KEY (MA_BAN),
  CHECK (SO_CHO>0)
);

CREATE TABLE NHA_CUNG_CAP (
  MA_NCC NUMBER,
  TEN_NCC VARCHAR2(150 CHAR) NOT NULL,
  SDT VARCHAR2(15 CHAR),
  DIA_CHI VARCHAR2(200 CHAR),
  EMAIL VARCHAR2(100 CHAR),
  PRIMARY KEY (MA_NCC)
);

CREATE TABLE NGUYEN_LIEU (
  MA_NL NUMBER,
  TEN_NL VARCHAR2(100 CHAR) NOT NULL,
  DON_VI VARCHAR2(20 CHAR),
  SO_LUONG_TON NUMBER(10,2) DEFAULT 0,
  TRANG_THAI VARCHAR2(20 CHAR),
  PRIMARY KEY (MA_NL),
  CHECK (SO_LUONG_TON>=0)
);

CREATE TABLE MON_AN (
  MA_MON NUMBER,
  MA_LOAI NUMBER NOT NULL,
  TEN_MON VARCHAR2(150 CHAR) NOT NULL,
  DON_VI VARCHAR2(20 CHAR),
  DON_GIA NUMBER(12,2) NOT NULL,
  TRANG_THAI VARCHAR2(20 CHAR),
  PRIMARY KEY (MA_MON),
  FOREIGN KEY (MA_LOAI) REFERENCES LOAI_MON(MA_LOAI),
  CHECK (DON_GIA>=0)
);

CREATE TABLE DAT_BAN (
  MA_DAT NUMBER,
  MA_KH NUMBER NOT NULL,
  MA_BAN NUMBER NOT NULL,
  NGAY_DAT DATE NOT NULL,
  SO_NGUOI NUMBER(3) NOT NULL,
  TIEN_COC NUMBER(12,2) DEFAULT 0,
  TRANG_THAI VARCHAR2(20 CHAR),
  PRIMARY KEY (MA_DAT),
  FOREIGN KEY (MA_KH) REFERENCES KHACH_HANG(MA_KH),
  FOREIGN KEY (MA_BAN) REFERENCES BAN_AN(MA_BAN),
  CHECK (SO_NGUOI>0),
  CHECK (TIEN_COC>=0)
);

CREATE TABLE HOA_DON (
  MA_HD NUMBER,
  MA_BAN NUMBER NOT NULL,
  MA_NV NUMBER NOT NULL,
  MA_KH NUMBER,
  NGAY_LAP DATE NOT NULL,
  GIAM_GIA NUMBER(12,2) DEFAULT 0,
  TONG_TIEN NUMBER(14,2),
  TRANG_THAI VARCHAR2(20 CHAR),
  PRIMARY KEY (MA_HD),
  FOREIGN KEY (MA_BAN) REFERENCES BAN_AN(MA_BAN),
  FOREIGN KEY (MA_NV) REFERENCES NHAN_VIEN(MA_NV),
  FOREIGN KEY (MA_KH) REFERENCES KHACH_HANG(MA_KH),
  CHECK (GIAM_GIA>=0),
  CHECK (TONG_TIEN>=0)
);

CREATE TABLE PHIEU_NHAP (
  MA_PN NUMBER,
  MA_NCC NUMBER NOT NULL,
  MA_NV NUMBER NOT NULL,
  NGAY_NHAP DATE NOT NULL,
  TONG_TIEN NUMBER(14,2),
  PRIMARY KEY (MA_PN),
  FOREIGN KEY (MA_NCC) REFERENCES NHA_CUNG_CAP(MA_NCC),
  FOREIGN KEY (MA_NV) REFERENCES NHAN_VIEN(MA_NV),
  CHECK (TONG_TIEN>=0)
);

CREATE TABLE CT_HOA_DON (
  MA_HD NUMBER,
  MA_MON NUMBER,
  SO_LUONG NUMBER(10,2) NOT NULL,
  DON_GIA NUMBER(12,2) NOT NULL,
  THANH_TIEN NUMBER(14,2),
  PRIMARY KEY (MA_HD, MA_MON),
  FOREIGN KEY (MA_HD) REFERENCES HOA_DON(MA_HD),
  FOREIGN KEY (MA_MON) REFERENCES MON_AN(MA_MON),
  CHECK (SO_LUONG>0),
  CHECK (DON_GIA>=0),
  CHECK (THANH_TIEN>=0)
);

CREATE TABLE CT_PHIEU_NHAP (
  MA_PN NUMBER,
  MA_NL NUMBER,
  SO_LUONG NUMBER(10,2) NOT NULL,
  DON_GIA NUMBER(12,2) NOT NULL,
  THANH_TIEN NUMBER(14,2),
  PRIMARY KEY (MA_PN, MA_NL),
  FOREIGN KEY (MA_PN) REFERENCES PHIEU_NHAP(MA_PN),
  FOREIGN KEY (MA_NL) REFERENCES NGUYEN_LIEU(MA_NL),
  CHECK (SO_LUONG>0),
  CHECK (DON_GIA>=0),
  CHECK (THANH_TIEN>=0)
);

