-- Run in the application's Oracle schema, after NHAN_VIEN has been created.
-- For a new inventory schema only. Existing schemas: see README.md.
WHENEVER SQLERROR EXIT SQL.SQLCODE
SET DEFINE OFF

CREATE SEQUENCE SEQ_NHA_CUNG_CAP START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE SEQ_NGUYEN_LIEU START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE SEQ_PHIEU_NHAP START WITH 1 INCREMENT BY 1 NOCACHE;

CREATE TABLE NHA_CUNG_CAP (
    MA_NCC NUMBER(19) PRIMARY KEY,
    TEN_NCC VARCHAR2(150 CHAR) NOT NULL,
    SDT VARCHAR2(15 CHAR),
    DIA_CHI VARCHAR2(200 CHAR),
    EMAIL VARCHAR2(100 CHAR)
);

CREATE TABLE NGUYEN_LIEU (
    MA_NL NUMBER(19) PRIMARY KEY,
    TEN_NL VARCHAR2(100 CHAR) NOT NULL,
    DON_VI VARCHAR2(20 CHAR) NOT NULL,
    SO_LUONG_TON NUMBER(10,2) DEFAULT 0 NOT NULL,
    TRANG_THAI VARCHAR2(20 CHAR) DEFAULT 'HOAT_DONG' NOT NULL,
    CONSTRAINT CK_NL_TON CHECK (SO_LUONG_TON >= 0),
    CONSTRAINT CK_NL_TRANG_THAI CHECK (TRANG_THAI IN ('HOAT_DONG', 'NGUNG_SU_DUNG'))
);

CREATE TABLE PHIEU_NHAP (
    MA_PN NUMBER(19) PRIMARY KEY,
    MA_NCC NUMBER(19) NOT NULL,
    MA_NV NUMBER(19) NOT NULL,
    NGAY_NHAP DATE NOT NULL,
    TONG_TIEN NUMBER(14,2) DEFAULT 0 NOT NULL,
    PHIEN_BAN NUMBER(19) DEFAULT 0 NOT NULL,
    CONSTRAINT FK_PN_NCC FOREIGN KEY (MA_NCC) REFERENCES NHA_CUNG_CAP(MA_NCC),
    CONSTRAINT FK_PN_NV FOREIGN KEY (MA_NV) REFERENCES NHAN_VIEN(MA_NV),
    CONSTRAINT CK_PN_TIEN CHECK (TONG_TIEN >= 0)
);

CREATE TABLE CT_PHIEU_NHAP (
    MA_PN NUMBER(19) NOT NULL,
    MA_NL NUMBER(19) NOT NULL,
    SO_LUONG NUMBER(10,2) NOT NULL,
    DON_GIA NUMBER(12,2) NOT NULL,
    THANH_TIEN NUMBER(14,2) NOT NULL,
    CONSTRAINT PK_CT_PHIEU_NHAP PRIMARY KEY (MA_PN, MA_NL),
    CONSTRAINT FK_CTPN_PN FOREIGN KEY (MA_PN) REFERENCES PHIEU_NHAP(MA_PN),
    CONSTRAINT FK_CTPN_NL FOREIGN KEY (MA_NL) REFERENCES NGUYEN_LIEU(MA_NL),
    CONSTRAINT CK_CTPN_SL CHECK (SO_LUONG > 0),
    CONSTRAINT CK_CTPN_GIA CHECK (DON_GIA >= 0),
    CONSTRAINT CK_CTPN_TIEN CHECK (THANH_TIEN >= 0)
);

CREATE INDEX IX_PN_NCC ON PHIEU_NHAP(MA_NCC);
CREATE INDEX IX_PN_NV ON PHIEU_NHAP(MA_NV);
CREATE INDEX IX_CTPN_NL ON CT_PHIEU_NHAP(MA_NL);

