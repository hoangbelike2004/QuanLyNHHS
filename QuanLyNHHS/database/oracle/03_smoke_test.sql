-- Run manually in an isolated Oracle schema after 01_inventory.sql.
-- The test rolls back its rows; sequence values are not rolled back by Oracle.
WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK
SET SERVEROUTPUT ON
SAVEPOINT INVENTORY_SMOKE;
DECLARE
    V_NCC NUMBER := SEQ_NHA_CUNG_CAP.NEXTVAL;
    V_NL NUMBER := SEQ_NGUYEN_LIEU.NEXTVAL;
    V_PN NUMBER := SEQ_PHIEU_NHAP.NEXTVAL;
    V_NV NUMBER;
    V_VALUE NUMBER;
BEGIN
    SELECT MIN(MA_NV) INTO V_NV FROM NHAN_VIEN;
    IF V_NV IS NULL THEN RAISE_APPLICATION_ERROR(-20100, 'Can it nhat mot nhan vien de test'); END IF;
    INSERT INTO NHA_CUNG_CAP(MA_NCC,TEN_NCC) VALUES (V_NCC,'Smoke test NCC');
    INSERT INTO NGUYEN_LIEU(MA_NL,TEN_NL,DON_VI) VALUES (V_NL,'Smoke test NL','kg');
    INSERT INTO PHIEU_NHAP(MA_PN,MA_NCC,MA_NV,NGAY_NHAP) VALUES (V_PN,V_NCC,V_NV,TRUNC(SYSDATE));
    INSERT INTO CT_PHIEU_NHAP(MA_PN,MA_NL,SO_LUONG,DON_GIA,THANH_TIEN) VALUES (V_PN,V_NL,1.25,10.01,0);
    SP_CAP_NHAT_TON_KHO(V_NL,1.25);
    SP_TINH_TONG_PHIEU_NHAP(V_PN);
    SELECT TONG_TIEN INTO V_VALUE FROM PHIEU_NHAP WHERE MA_PN=V_PN;
    IF V_VALUE <> 12.51 THEN RAISE_APPLICATION_ERROR(-20101,'Tong tien sai'); END IF;
    SELECT SO_LUONG_TON INTO V_VALUE FROM NGUYEN_LIEU WHERE MA_NL=V_NL;
    IF V_VALUE <> 1.25 THEN RAISE_APPLICATION_ERROR(-20102,'Ton kho sai'); END IF;
    BEGIN
        SP_CAP_NHAT_TON_KHO(V_NL,-2);
        RAISE_APPLICATION_ERROR(-20103,'Khong chan duoc ton am');
    EXCEPTION WHEN OTHERS THEN IF SQLCODE <> -20002 THEN RAISE; END IF;
    END;
    BEGIN
        INSERT INTO CT_PHIEU_NHAP(MA_PN,MA_NL,SO_LUONG,DON_GIA,THANH_TIEN) VALUES (V_PN,V_NL,-1,1,0);
        RAISE_APPLICATION_ERROR(-20104,'Khong chan duoc so luong am');
    EXCEPTION WHEN OTHERS THEN IF SQLCODE <> -20005 THEN RAISE; END IF;
    END;
    DBMS_OUTPUT.PUT_LINE('PASS: money rounding, stock adjustment, negative guards');
END;
/
ROLLBACK TO INVENTORY_SMOKE;
